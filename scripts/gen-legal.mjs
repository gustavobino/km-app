// Embeds legal/*.md into lib/legal/content.generated.ts, because serverless
// platforms like Cloudflare Workers have no filesystem at runtime.
// Run after editing legal/*.md:  node scripts/gen-legal.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const docs = ["termos", "privacidade"];
const body = docs
  .map((name) => `  ${name}: ${JSON.stringify(readFileSync(join(root, "legal", `${name}.md`), "utf8"))},`)
  .join("\n");
writeFileSync(
  join(root, "lib/legal/content.generated.ts"),
  `// GENERATED by scripts/gen-legal.mjs from legal/*.md — do not edit by hand.\nexport const LEGAL_MARKDOWN = {\n${body}\n} as const;\n`,
);
console.log("legal content generated");
